def make_records():
    seen = set()
    records = []
    for label, rows in MANUAL.items():
        assert len(rows) == 12, (label, len(rows))
        for i, text in enumerate(rows):
            key = text.strip().casefold()
            assert key not in seen
            seen.add(key)
            records.append({
                "id": f"manual-{label.lower()}-{i:02d}",
                "text": text,
                "intent": label,
                "slots": [],  # Нужна только классификация намерения; слоты не размечены.
                "source": "manual_authored_holdout",
            })
    return records


def main():
    path = ROOT / "data" / "manual_holdout.jsonl"
    with path.open("w", encoding="utf-8") as f:
        for row in make_records():
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"{len(make_records())} вручную составленных фраз -> {path}")


if __name__ == "__main__":
    main()
